#!/usr/bin/env bash
# Builds Kiriglyph and installs it for the current user: a launcher, a desktop
# file named after the app ID (GNOME stores the screenshot grant against it),
# and an autostart entry that starts the app hidden at login. It never changes
# GNOME settings or keybindings.
#
# Usage: ./scripts/install-desktop.sh [--debug]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FLUTTER="$ROOT/.tools/flutter/bin/flutter"
WORKER_ROOT="$ROOT/worker"
WORKER_PYTHON="$WORKER_ROOT/.venv/bin/python"
APP_ID="dev.kiriglyph.Kiriglyph"
BINARY_NAME="kiriglyph"

DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
BUNDLE_DIR="$DATA_HOME/kiriglyph/bundle"
ICON_DIR="$DATA_HOME/icons/hicolor/symbolic/apps"
# The app shows this path as its shortcut command; keep both in sync with
# app/lib/app/app_identity.dart.
LAUNCHER="$HOME/.local/bin/kiriglyph"
DESKTOP_FILE="$DATA_HOME/applications/$APP_ID.desktop"
AUTOSTART_FILE="$CONFIG_HOME/autostart/$APP_ID.desktop"

MODE="release"
case "${1:-}" in
  "") ;;
  --debug) MODE="debug" ;;
  *)
    printf 'Usage: %s [--debug]\n' "$0" >&2
    exit 2
    ;;
esac

if [[ ! -x "$FLUTTER" || ! -x "$WORKER_PYTHON" ]]; then
  printf 'Development dependencies are missing. Run ./scripts/bootstrap.sh first.\n' >&2
  exit 1
fi

# Desktop-entry Exec values would need extra escaping for other characters.
if [[ ! "$LAUNCHER" =~ ^[A-Za-z0-9/._-]+$ ]]; then
  printf 'Unsupported characters in the launcher path: %s\n' "$LAUNCHER" >&2
  exit 1
fi

sh_quote() {
  local quote="'" escaped="'\\''"
  printf "'%s'" "${1//"$quote"/"$escaped"}"
}

instance_running() {
  gdbus call --session --dest org.freedesktop.DBus \
    --object-path /org/freedesktop/DBus \
    --method org.freedesktop.DBus.NameHasOwner "$APP_ID" 2>/dev/null |
    grep -q true
}

stop_running_instance() {
  if [[ -x "$LAUNCHER" ]] && instance_running; then
    printf 'Stopping the running Kiriglyph instance...\n'
    timeout 10 "$LAUNCHER" --quit >/dev/null 2>&1 || true
    for _ in $(seq 50); do
      instance_running || return 0
      sleep 0.1
    done
    printf 'Kiriglyph did not stop; quit it and run this script again.\n' >&2
    exit 1
  fi
}

printf 'Building the Linux %s bundle...\n' "$MODE"
(cd "$ROOT/app" && "$FLUTTER" build linux "--$MODE")

shopt -s nullglob
bundles=("$ROOT"/app/build/linux/*/"$MODE"/bundle)
shopt -u nullglob
if ((${#bundles[@]} != 1)); then
  printf 'Expected exactly one built bundle, found %d.\n' "${#bundles[@]}" >&2
  exit 1
fi

stop_running_instance

rm -rf "$BUNDLE_DIR"
mkdir -p "$BUNDLE_DIR" "$(dirname "$LAUNCHER")" "$(dirname "$DESKTOP_FILE")" \
  "$(dirname "$AUTOSTART_FILE")" "$ICON_DIR"
cp -a "${bundles[0]}/." "$BUNDLE_DIR/"
cp "$ROOT/app/assets/icons/kiriglyph-symbolic.svg" "$ICON_DIR/kiriglyph-symbolic.svg"
cp "$ROOT/app/assets/icons/kiriglyph-attention-symbolic.svg" "$ICON_DIR/kiriglyph-attention-symbolic.svg"
cp "$ROOT/app/assets/icons/kiriglyph-busy-symbolic.svg" "$ICON_DIR/kiriglyph-busy-symbolic.svg"

cat >"$LAUNCHER" <<EOF
#!/bin/sh
# Generated by scripts/install-desktop.sh; removed by uninstall-desktop.sh.
export KIRIGLYPH_WORKER_ROOT=$(sh_quote "$WORKER_ROOT")
export KIRIGLYPH_WORKER_PYTHON=$(sh_quote "$WORKER_PYTHON")
unset KIRIGLYPH_DEV_INSTANCE
exec $(sh_quote "$BUNDLE_DIR/$BINARY_NAME") "\$@"
EOF
chmod 755 "$LAUNCHER"

cat >"$DESKTOP_FILE" <<EOF
[Desktop Entry]
Type=Application
Name=Kiriglyph
Comment=Select and copy text from anything on screen
Exec=$LAUNCHER
Icon=kiriglyph-symbolic
Terminal=false
Categories=Utility;
Keywords=OCR;text;screenshot;copy;
StartupNotify=true
StartupWMClass=$APP_ID
EOF

cat >"$AUTOSTART_FILE" <<EOF
[Desktop Entry]
Type=Application
Name=Kiriglyph
Comment=Keeps Kiriglyph ready for its selection shortcut
Exec=$LAUNCHER --background
Icon=kiriglyph-symbolic
Terminal=false
NoDisplay=true
X-GNOME-Autostart-enabled=true
EOF

if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "$(dirname "$DESKTOP_FILE")" >/dev/null 2>&1 || true
fi
if command -v gtk-update-icon-cache >/dev/null 2>&1; then
  gtk-update-icon-cache -q "$DATA_HOME/icons/hicolor" >/dev/null 2>&1 || true
fi

setsid -f "$LAUNCHER" --background </dev/null >/dev/null 2>&1

cat <<EOF

Kiriglyph is installed and running in the background.

  Launcher:   $LAUNCHER
  App:        $DESKTOP_FILE
  Autostart:  $AUTOSTART_FILE

Next steps:
  1. Open Kiriglyph from the app grid and enable instant capture once.
     GNOME asks for screen access only while the Kiriglyph window is focused.
  2. Add a GNOME custom shortcut (Settings > Keyboard > View and Customize
     Shortcuts > Custom Shortcuts) with this command:
       $LAUNCHER --select
  3. Optional Subject mode models: run (cd "$WORKER_ROOT" && ../.tools/uv-bin/uv run --locked kiriglyph-fetch-models).
EOF
